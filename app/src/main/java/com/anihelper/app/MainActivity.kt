    private fun showHome() {
        root = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            setPadding(dp(16), dp(18), dp(16), dp(32))
            setBackgroundColor(Color.rgb(246, 249, 255))
        }

        root.addView(titleText("🎓 Школьник 9 класс", 30f))
        root.addView(bodyText("Офлайн-помощник: правила, формулы, подсказки и разобранные решения по основным предметам.").apply {
            setPadding(0, dp(6), 0, dp(14))
        })

        val search = EditText(this).apply {
            hint = "Поиск: дискриминант, Ом, пассивный залог…"
            textSize = 16f
            setPadding(dp(16), dp(12), dp(16), dp(12))
            background = rounded(Color.WHITE, 18)
            setSingleLine(true)
        }
        root.addView(search, LinearLayout.LayoutParams(-1, -2).apply { bottomMargin = dp(14) })

        val container = LinearLayout(this).apply { orientation = LinearLayout.VERTICAL }
        root.addView(container)

        fun render(query: String) {
            container.removeAllViews()
            val q = query.trim().lowercase(Locale.getDefault())
            if (q.isBlank()) {
                subjects.forEach { container.addView(subjectCard(it)) }
            } else {
                var found = 0
                subjects.forEach { subject ->
                    subject.lessons.filter {
                        it.title.lowercase().contains(q) ||
                            it.rule.lowercase().contains(q) ||
                            it.hint.lowercase().contains(q) ||
                            subject.name.lowercase().contains(q)
                    }.forEach { lesson ->
                        found++
                        container.addView(searchResultCard(subject, lesson))
                    }
                }
                if (found == 0) container.addView(bodyText("Ничего не найдено. Попробуй другое слово."))
            }
        }

        search.addTextChangedListener(object : TextWatcher {
            override fun beforeTextChanged(s: CharSequence?, start: Int, count: Int, after: Int) {}
            override fun onTextChanged(s: CharSequence?, start: Int, before: Int, count: Int) { render(s?.toString().orEmpty()) }
            override fun afterTextChanged(s: Editable?) {}
        })

        render("")
        setContentView(ScrollView(this).apply { addView(root) })
    }

    private fun subjectCard(subject: Subject): View = LinearLayout(this).apply {
        orientation = LinearLayout.VERTICAL
        setPadding(dp(18), dp(16), dp(18), dp(16))
        background = rounded(Color.WHITE, 20)
        isClickable = true
        isFocusable = true
        setOnClickListener { showSubject(subject) }
        addView(titleText("${subject.emoji} ${subject.name}", 21f))
        addView(bodyText(subject.description).apply { setPadding(0, dp(5), 0, dp(4)) })
        addView(smallText("Тем: ${subject.lessons.size}  •  открыть →"))
        layoutParams = LinearLayout.LayoutParams(-1, -2).apply { bottomMargin = dp(12) }
    }

    private fun searchResultCard(subject: Subject, lesson: Lesson): View = LinearLayout(this).apply {
        orientation = LinearLayout.VERTICAL
        setPadding(dp(16), dp(14), dp(16), dp(14))
        background = rounded(Color.WHITE, 18)
